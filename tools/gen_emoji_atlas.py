COLS = 16          # grid columns
BASE = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/"
OUT_PNG = "assets/emoji_atlas.png"
OUT_H   = "src/ui/emoji_atlas.h"

