#!/usr/bin/env python3
"""Build the bundled emoji atlas for Cordless.

Fetches Twemoji PNGs, packs them into one grid texture, and writes the C lookup
table. Run from the repo root:

    python3 tools/gen_emoji_atlas.py
"""
import io, os, sys, urllib.request
