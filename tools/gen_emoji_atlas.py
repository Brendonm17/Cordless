def main():
    keys, seen = [], set()
    for k in KEYS:
        if k not in seen:
            seen.add(k); keys.append(k)

    imgs = []
    for k in keys:
        try:
            with urllib.request.urlopen(BASE + k + ".png", timeout=30) as r:
                data = r.read()
            im = Image.open(io.BytesIO(data)).convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
            imgs.append((k, im))
        except Exception as e:
            print(f"  skip {k}: {e}", file=sys.stderr)

    n = len(imgs)
    rows = (n + COLS - 1) // COLS
    atlas = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, (k, im) in enumerate(imgs):
        x, y = (i % COLS) * CELL, (i // COLS) * CELL
        atlas.paste(im, (x, y))
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    atlas.save(OUT_PNG)
    print(f"wrote {OUT_PNG}  {atlas.width}x{atlas.height}  {n} emoji")

    with open(OUT_H, "w") as f:
        f.write("// Generated by tools/gen_emoji_atlas.py - do not edit.\n")
        f.write("#ifndef CORDLESS_UI_EMOJI_ATLAS_H\n#define CORDLESS_UI_EMOJI_ATLAS_H\n\n")
        f.write(f"#define EMOJI_CELL {CELL}\n#define EMOJI_COLS {COLS}\n")
        f.write(f"#define EMOJI_COUNT {n}\n\n")
        f.write("typedef struct { const char *key; short cell; } emoji_entry;\n\n")
        f.write("static const emoji_entry EMOJI_TABLE[EMOJI_COUNT] = {\n")
        for i, (k, _) in enumerate(imgs):
            f.write(f'    {{"{k}", {i}}},\n')
        f.write("};\n\n#endif\n")
    print(f"wrote {OUT_H}")

if __name__ == "__main__":
    main()
